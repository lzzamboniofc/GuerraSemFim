'use strict';
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..'),memory=new Map(),callbacks={},dom={innerHTML:'',className:'',querySelector:()=>null};
const window={innerWidth:390,scrollTo:()=>{},addEventListener:(name,fn)=>callbacks[name]=fn};
const document={querySelector:sel=>sel==='#app'?dom:null,querySelectorAll:()=>[],addEventListener:(name,fn)=>callbacks[name]=fn,body:{appendChild:()=>{}},createElement:()=>({setAttribute:()=>{},remove:()=>{}})};
const localStorage={getItem:k=>memory.get(k)||null,setItem:(k,v)=>memory.set(k,String(v)),removeItem:k=>memory.delete(k)};
const ctx={window,document,localStorage,Date,Math,JSON,console,setInterval:()=>0,setTimeout:()=>0};
vm.createContext(ctx);
for(const file of ['data','war','ai','campaign','expansion','engine'])vm.runInContext(fs.readFileSync(path.join(root,'js',file+'.js'),'utf8'),ctx,{filename:file});
const E=window.GSF,st=E.newGame();
assert.equal(E.viewMode(st),'original');assert(E.validateState(st));
const old=JSON.parse(JSON.stringify(st));delete old.preferences.viewMode;
assert(E.validateState(old));assert.equal(E.viewMode(old),'original');
assert.equal(E.setViewMode(st,'compact').ok,true);assert(E.save(st));
assert.equal(E.load().preferences.viewMode,'compact');
assert.equal(E.setViewMode(st,'original').ok,true);
assert.equal(E.setViewMode(st,'invalid').ok,false);
st.preferences.viewMode='invalid';assert(!E.validateState(st));
st.preferences.viewMode='original';assert(E.save(st));
require('./_load-ui')(ctx);
const click=data=>callbacks.click({target:{closest:()=>({dataset:data})}});
assert.equal(dom.className,'view-original');
click({visualMode:'compact'});assert.equal(dom.className,'view-compact');
assert.equal(JSON.parse(memory.get(E.KEY)).preferences.viewMode,'compact');
click({nav:'settings'});assert(dom.innerHTML.includes('id="visual-mode"'));
callbacks.change({target:{id:'visual-mode',value:'original'}});
assert.equal(dom.className,'view-original');
click({nav:'fields'});assert(dom.innerHTML.includes('data-visual-mode="compact"'));
click({nav:'map'});assert.equal((dom.innerHTML.match(/data-tile-x=/g)||[]).length,25);
const css=fs.readFileSync(path.join(root,'styles-fit.css'),'utf8');
assert(css.includes('.view-compact .scene.town-board'));assert(css.includes('.view-original .scene.town-board'));
console.log('✓ UI v0.8.6: modo original, grade opcional, salvamento e saves antigos');
