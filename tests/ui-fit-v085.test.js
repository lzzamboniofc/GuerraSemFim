/* Protege o layout sem rolagem horizontal, mantendo as ações do jogo. */
'use strict';
const fs=require('fs'),path=require('path'),vm=require('vm'),assert=require('node:assert/strict');
const root=path.join(__dirname,'..'),css=fs.readFileSync(path.join(root,'styles-fit.css'),'utf8');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const callbacks={},dom={innerHTML:''},storage=new Map();
const window={innerWidth:390,addEventListener(type,handler){callbacks[type]=handler},scrollTo:()=>{}};
const document={querySelector(sel){return sel==='#app'?dom:null},querySelectorAll:()=>[],addEventListener(type,handler){callbacks[type]=handler},body:{appendChild:()=>{}},createElement:()=>({setAttribute:()=>{},remove:()=>{}})};
const context={window,document,localStorage:{getItem:key=>storage.get(key)||null,setItem:(key,val)=>storage.set(key,val),removeItem:key=>storage.delete(key)},Date,Math,JSON,console,setInterval:()=>0,setTimeout:()=>0};
vm.createContext(context);
for(const file of ['data','war','ai','campaign','expansion','engine'])vm.runInContext(fs.readFileSync(path.join(root,'js',file+'.js'),'utf8'),context,{filename:file});
window.GSF.newGame();
require('./_load-ui')(context);
const click=data=>callbacks.click({target:{closest:()=>({dataset:data})}});
assert(html.includes('styles-fit.css'),'Nova folha adaptativa ausente');
assert(css.includes('grid-template-columns:repeat(2,minmax(0,1fr))'),'Cartões não suportam duas colunas no celular');
assert(css.includes('left:auto!important')&&css.includes('top:auto!important'),'Posições antigas devem ser anuladas');
assert(css.includes('overflow:visible;scroll-snap-type:none'),'O menu não deve arrastar lateralmente');
click({nav:'village'});
assert(dom.innerHTML.includes('board-intro'),'Edifícios não estão em grade adaptativa');
assert(dom.innerHTML.includes('data-slot="0"'));
assert(dom.innerHTML.includes('data-open-resource="wood"'));
click({toggleMenu:''});assert(dom.innerHTML.includes('nav-expanded'),'O menu expandido não abre');
click({nav:'fields'});assert(!dom.innerHTML.includes('nav-expanded'),'Navegação deve recolher o menu');
assert(dom.innerHTML.includes('field-name'),'Recursos devem identificar cada campo');
click({nav:'map'});
assert(dom.innerHTML.includes('data-map-columns="5"'));
assert.equal((dom.innerHTML.match(/data-tile-x=/g)||[]).length,25,'Celular deve mostrar 25 casas');
window.innerWidth=768;callbacks.resize();
assert(dom.innerHTML.includes('data-map-columns="7"'));
assert.equal((dom.innerHTML.match(/data-tile-x=/g)||[]).length,49,'Tablet deve mostrar 49 casas');
window.innerWidth=1024;callbacks.resize();
assert(dom.innerHTML.includes('data-map-columns="9"'));
window.innerWidth=1600;callbacks.resize();
assert(dom.innerHTML.includes('data-map-columns="11"'));
click({nav:'village'});click({slot:'0'});
assert(dom.innerHTML.includes('modal-inspector'),'Modal de edifício deve continuar abrindo');
console.log('✓ UI v0.8.5: edifícios, campos, recursos, menu, mapa adaptativo e modais');
