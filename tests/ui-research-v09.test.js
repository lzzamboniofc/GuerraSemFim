'use strict';
const fs=require('node:fs'),vm=require('node:vm'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..'),db=new Map(),callbacks={},dom={innerHTML:'',className:'',querySelector:()=>null};
const window={innerWidth:390,addEventListener:()=>{},scrollTo:()=>{}};
const document={querySelector:x=>x==='#app'?dom:null,querySelectorAll:()=>[],addEventListener:(n,fn)=>callbacks[n]=fn,body:{appendChild:()=>{}},createElement:()=>({setAttribute:()=>{},remove:()=>{}})};
const ctx={window,document,localStorage:{getItem:k=>db.get(k)||null,setItem:(k,v)=>db.set(k,String(v)),removeItem:k=>db.delete(k)},console,Date,JSON,Math,setInterval:()=>0,setTimeout:()=>0};
vm.createContext(ctx);
for(const f of ['data','war','ai','campaign','expansion','engine'])vm.runInContext(fs.readFileSync(path.join(root,'js',f+'.js'),'utf8'),ctx,{filename:f});
const st=window.GSF.newGame(),v=window.GSF.active(st);v.buildings.barracks=3;v.buildings.academy=1;
